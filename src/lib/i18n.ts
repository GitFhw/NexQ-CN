function normalizeKey(source: string): string {
  return source
    .replace(/&amp;/g, "&")
    .replace(/&nbsp;/g, " ")
    .replace(/&apos;/g, "'")
    .replace(/&middot;/g, "·")
    .replace(/&rarr;/g, "→")
    .replace(/\s+/g, " ")
    .trim();
}

/** Translate one English UI string, retaining whitespace around JSX text nodes. */
export function t(source: string, values?: Record<string, string | number>, locale?: UILocale): string {
  const activeLocale = locale ?? useConfigStore.getState().uiLocale;
  if (activeLocale !== "zh-CN") return interpolate(source, values);

  const leading = source.match(/^\s*/)?.[0] ?? "";
  const trailing = source.match(/\s*$/)?.[0] ?? "";
  const key = normalizeKey(source);
  let translated = zhCN[key] ?? source.trim();
  translated = interpolate(translated, values);
  return `${leading}${translated}${trailing}`;
}

function interpolate(source: string, values?: Record<string, string | number>): string {
  if (!values) return source;
  return source.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match
  );
}

export function useUiLocale(): UILocale {
  const locale = useConfigStore((state) => state.uiLocale);
  if (typeof document !== "undefined") document.documentElement.lang = locale;
  return locale;
}
