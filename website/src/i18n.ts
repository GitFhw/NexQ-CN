function normalize(source: string): string {
  return source
    .replace(/&amp;/g, "&")
    .replace(/&nbsp;/g, " ")
    .replace(/&apos;/g, "'")
    .replace(/&bull;/g, "•")
    .replace(/&mdash;/g, "—")
    .replace(/&ndash;/g, "–")
    .replace(/&middot;/g, "·")
    .replace(/&lsquo;|&rsquo;/g, "'")
    .replace(/&copy;/g, "©")
    .replace(/\s+/g, " ")
    .trim();
}

export function t(source: string, locale: WebsiteLocale): string {
  if (locale !== "zh-CN") return source;
  const translated = zhCN[normalize(source)];
  return translated ?? source;
}
